/** Typographic apostrophes are folded to the plain one the bank uses. */
const fold = (s: string): string => s.trim().replace(/[’ʼ]/g, "'");

const FOLDED = new Map(Object.entries(EN).map(([k, v]) => [fold(k), v]));

/** The category as it should be shown in the current language. */
export function categoryLabel(category: string): string {
  return currentLang() === 'en' ? (FOLDED.get(fold(category)) ?? category) : category;
}
